export type TranslationKey = string;

export interface LanguageContextValue {
  language: AppLanguage;
  direction: AppDirection;
  isRtl: boolean;
  setLanguage: (language: AppLanguage) => void;
  toggleLanguage: () => void;
  t: (key: TranslationKey, values?: TranslationValues) => string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

const readStoredLanguage = (): AppLanguage => {
  if (typeof window === "undefined") return DEFAULT_LANGUAGE;

  try {
    const raw = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
    return raw === "en" || raw === "fr" || raw === "ar"
      ? raw
      : DEFAULT_LANGUAGE;
  } catch {
    return DEFAULT_LANGUAGE;
  }
};

const applyLanguageToDocument = (language: AppLanguage): void => {
  if (typeof document === "undefined") return;

  const direction: AppDirection = language === "ar" ? "rtl" : "ltr";
  document.documentElement.lang = language;
  document.documentElement.dir = direction;
  document.documentElement.dataset.language = language;
};

const interpolateTranslation = (
  template: string,
  values?: TranslationValues,
): string => {
  if (!values) return template;

  return template.replace(/\{(\w+)\}/g, (match, token) => {
    const value = values[token];
    return value === undefined || value === null ? match : String(value);
  });
};

export const LanguageProvider = ({ children }: { children: ReactNode }) => {
  const [language, setLanguageState] = useState<AppLanguage>(readStoredLanguage);

  useEffect(() => {
    applyLanguageToDocument(language);

    try {
      window.localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
    } catch {
      // Ignore storage errors and keep the in-memory preference.
    }
  }, [language]);

  const value = useMemo<LanguageContextValue>(() => {
    const direction: AppDirection = language === "ar" ? "rtl" : "ltr";
    const currentTranslations = translations[language] as Record<string, string>;
    const fallbackTranslations = translations.en as Record<string, string>;

    return {
      language,
      direction,
      isRtl: direction === "rtl",
      setLanguage: (nextLanguage) => setLanguageState(nextLanguage),
      toggleLanguage: () =>
        setLanguageState((current) =>
          current === "en" ? "fr" : current === "fr" ? "ar" : "en",
        ),
      t: (key, values) =>
        interpolateTranslation(
          currentTranslations[key] ?? fallbackTranslations[key] ?? key,
          values,
        ),
    };
  }, [language]);

  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useAppLanguage = (): LanguageContextValue => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error("useAppLanguage must be used inside LanguageProvider");
  }

  return context;
};
